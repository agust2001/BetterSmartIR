export function translator(language) {
  const texts = language?.startsWith("es") ? TEXTS.es : TEXTS.en;
  return (key, params = {}) =>
    (texts[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => params[name] ?? "");
}
